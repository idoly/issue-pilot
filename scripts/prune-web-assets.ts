// Keeps only the current Web build. Dry-run unless --apply is given.
import { lstat, readFile, readdir, rm } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";
import { applicationConfig } from "../src/config.ts";
import { isHashedWebAsset } from "../src/http/web-assets.ts";

interface ManifestChunk {
  file: string;
  css?: string[];
  assets?: string[];
  imports?: string[];
  dynamicImports?: string[];
}

async function currentBuildFiles(root: string): Promise<Set<string>> {
  for (const dir of [root, path.join(root, "assets"), path.join(root, ".vite")]) {
    if (!(await lstat(dir)).isDirectory()) throw new Error(`web_expected_directory:${dir}`);
  }
  const name = ".vite/manifest.json";
  for (const file of [name, "index.html"]) {
    if (!(await lstat(path.join(root, file))).isFile()) throw new Error(`web_expected_regular_file:${file}`);
  }
  let manifest: Record<string, ManifestChunk>;
  try {
    manifest = JSON.parse(await readFile(path.join(root, name), "utf8")) as Record<string, ManifestChunk>;
  } catch (error) {
    throw new Error(`web_manifest_unreadable:${name}`, { cause: error });
  }
  const files = new Set<string>();
  for (const chunk of Object.values(manifest)) {
    for (const key of [...(chunk.imports ?? []), ...(chunk.dynamicImports ?? [])]) {
      if (!Object.hasOwn(manifest, key)) throw new Error(`web_manifest_chunk_missing:${key}`);
    }
    for (const file of [chunk.file, ...(chunk.css ?? []), ...(chunk.assets ?? [])]) files.add(file);
  }
  for (const file of files) {
    if (!/^assets\/[^/]+$/.test(file)) throw new Error(`web_manifest_unexpected_path:${name}:${file}`);
    const info = await lstat(path.join(root, file)).catch(() => undefined);
    if (!info?.isFile()) throw new Error(`web_manifest_file_missing:${name}:${file}`);
  }
  const html = await readFile(path.join(root, "index.html"), "utf8");
  const refs = [...html.matchAll(/(?:src|href)="\/(assets\/[^"?#]+)"/g)].map((match) => match[1]!);
  for (const ref of refs) {
    if (files.has(ref)) continue;
    if (isHashedWebAsset(ref)) throw new Error(`web_manifest_html_mismatch:index.html:${ref}`);
    const info = await lstat(path.join(root, ref)).catch(() => undefined);
    if (!info?.isFile()) throw new Error(`web_html_file_missing:index.html:${ref}`);
  }
  if (!refs.includes(manifest["index.html"]?.file ?? "")) throw new Error("web_html_entry_missing:index.html");
  return files;
}

export async function planWebAssetPrune(root: string): Promise<{ keep: Set<string>; remove: string[] }> {
  const keep = await currentBuildFiles(root);
  const remove: string[] = [];
  for (const entry of await readdir(path.join(root, "assets"), { withFileTypes: true })) {
    // Stable public files and icon directories are not identifiable as retired bundles.
    if (!entry.isFile()) continue;
    const file = `assets/${entry.name}`;
    if (isHashedWebAsset(file) && !keep.has(file.replace(/\.(?:br|gz)$/, ""))) remove.push(file);
  }
  // These two exact files were generated by older releases. Never follow their contents or sweep .vite/.
  for (const file of ["index.previous.html", ".vite/manifest.previous.json"]) {
    const info = await lstat(path.join(root, file)).catch((error: NodeJS.ErrnoException) => {
      if (error.code !== "ENOENT") throw error;
    });
    if (!info) continue;
    if (!info.isFile()) throw new Error(`web_expected_regular_file:${file}`);
    remove.push(file);
  }
  return { keep, remove: remove.sort() };
}

async function main(): Promise<void> {
  const { values, positionals } = parseArgs({ allowPositionals: true, options: { apply: { type: "boolean" }, "check-current": { type: "boolean" } } });
  if (positionals.length > 1 || (values.apply && values["check-current"])) throw new Error("usage: prune-web-assets.ts [web-root] [--apply | --check-current]");
  const root = path.resolve(positionals[0] ?? applicationConfig.webRoot);
  if (values["check-current"]) {
    await currentBuildFiles(root);
    return;
  }
  const { keep, remove } = await planWebAssetPrune(root);
  console.log(`${values.apply ? "Removing" : "Would remove"} ${remove.length} files; keeping ${keep.size} current manifest files in ${root}`);
  for (const file of remove) {
    console.log(file);
    if (values.apply) await rm(path.join(root, file));
  }
}

if (import.meta.main) {
  try {
    await main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
